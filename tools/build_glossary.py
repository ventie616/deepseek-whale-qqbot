items = []
for line in RAW.strip().splitlines():
    parts = line.split("|")
    if len(parts) < 5:
        continue
    term, aliases, cat, meaning, tone = parts[:5]
    safety = parts[5] if len(parts) > 5 else ("nsfw" if tone == "慎用" else "ok")
    if tone == "慎用":
        safety = "nsfw"
    items.append(
        {
            "term": term.strip(),
            "aliases": [a.strip() for a in aliases.split(",") if a.strip()],
            "cat": cat.strip(),
            "meaning": meaning.strip(),
            "tone": tone.strip(),
            "safety": safety,
        }
    )

seen = set()
uniq = []
for it in items:
    if it["term"] in seen:
        continue
    seen.add(it["term"])
    uniq.append(it)

OUT.write_text(json.dumps(uniq, ensure_ascii=False, indent=2), encoding="utf-8")
print(f"已写入 {len(uniq)} 条 -> {OUT}")
from collections import Counter

print("分类:", dict(Counter(i["cat"] for i in uniq)))
print("安全:", dict(Counter(i["safety"] for i in uniq)))
