def parse(line: str) -> dict | None:
    parts = line.split("|")
    if len(parts) < 3:
        return None
    title = parts[0].strip()
    if not title:
        return None
    aliases = []
    if "(" in title and title.endswith(")"):
        title, alias = title.split("(", 1)
        aliases.append(alias.rstrip(")").strip())
        title = title.strip()
    return {
        "title": title,
        "aliases": aliases,
        "type": parts[1].strip() if len(parts) > 1 else "",
        "year": parts[2].strip() if len(parts) > 2 else "",
        "tags": [t.strip() for t in (parts[3] if len(parts) > 3 else "").split(",") if t.strip()],
        "one_liner": (parts[4] if len(parts) > 4 else "").strip(),
    }


items, seen = [], set()
for line in RAW.splitlines():
    if not line.strip():
        continue
    it = parse(line)
    if it and it["title"] not in seen:
        seen.add(it["title"])
        items.append(it)

OUT.write_text(
    json.dumps({"updated": datetime.now().strftime("%Y-%m-%d"), "items": items},
               ensure_ascii=False, indent=2),
    encoding="utf-8",
)
