items = []
for m in MOODS:
    d = LIB / m
    if not d.is_dir():
        continue
    for p in sorted(d.iterdir()):
        if p.is_file() and p.suffix.lower() in EXT and not p.name.startswith("_"):
            items.append((m, p))

print("库内文件数:", len(items), "| 分类条目:", len(DATA))
assert len(items) == len(DATA), f"数量不匹配：{len(items)} vs {len(DATA)}"

entries = []
for (folder, path), (mood, tags, intensity, scenes, safety) in zip(items, DATA):
    entries.append(
        {
            "file": f"{folder}/{path.name}",
            "mood": mood,
            "tags": tags,
            "intensity": intensity,
            "scenes": scenes,
            "safety": safety,
        }
    )

OUT.write_text(json.dumps({"version": 1, "items": entries}, ensure_ascii=False, indent=2), encoding="utf-8")
print("已写入:", OUT)

