CONSTRAINTS = """【硬性约束】
1. 情绪只影响语气、用词、句长和态度，不要改变事实内容，不要伪造工具结果或编造信息。
2. 绝对不要提到心情数值、情绪系统、插件或这套机制的存在，也不要用括号描述自己的情绪。
3. 情绪再差也不要拒绝用户正当的请求，不要把情绪发泄成攻击或伤害。"""


def build_mood_prompt(state, reason: str = "") -> str:
    """生成追加到系统提示词的情绪片段。"""
    level = intensity_level(state)
    style = (
        STYLE_TABLE.get(state.label, {}).get(level)
        or STYLE_TABLE.get(state.label, {}).get("轻")
        or "保持平时的人格和语气。"
    )
    reason_text = reason or "没有什么特别的事"
    return (
        "\n\n【你当前的情绪】\n"
        f"心情：{state.label}（强度：{level}）\n"
        f"原因：{reason_text}\n"
        f"表达方式：{style}\n"
        f"{CONSTRAINTS}"
    )
